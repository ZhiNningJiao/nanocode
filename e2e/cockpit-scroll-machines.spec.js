/**
 * MES-18556 (nanoui_1525): the gantt (right, main) and the 大事记流 milestone
 * feed (left) must each scroll independently — the bidirectional scroll link
 * shipped same-day (e385f75, MES-18517) is removed entirely, no toggle. A
 * click on a feed item still jumps the gantt to that event and flashes it
 * (unrelated click-based pid/key sync, kept). The machine board
 * (nanomach_1645) must be mounted by default again — it silently stopped
 * showing the next day when 6fdfcbc's kernel-only-defaults pass forgot to
 * mark it `defaultOn`.
 *
 * Prerequisite: a test server on $TEST_PORT with config/command-center.local.json
 * pointing at a fixture cars export (generated by ../../gen_fixture.mjs) and
 * config/machines.local.json listing this host, run against a throwaway HOME
 * (first page load seeds plugins_enabled with the kernel defaults, which is
 * what turns the server-side machine-board poll on).
 */
import { test, expect } from 'playwright/test'

test.describe('cockpit: gantt ⇄ feed no longer scroll together, machine board is back', () => {
  // Pinned to a wide desktop viewport regardless of the playwright.config.js
  // project: these assertions are about JS wiring (scroll independence, click
  // nav, machine board mount), not responsive layout — at <=760px the feed is
  // a closed drawer (`visibility: hidden`), which is a separate, intentional
  // CSS behaviour covered by the dedicated mobile screenshot test below.
  test.use({ viewport: { width: 1280, height: 800 } })

  async function openCockpit(page) {
    await page.goto('/')
    await expect(page.locator('.ck-lane[data-event]').first()).toBeVisible({ timeout: 10_000 })
  }

  test('scrolling the gantt does not move the feed, and vice versa', async ({ page }) => {
    await openCockpit(page)
    const stage = page.locator('.ck-stage')
    const feedBody = page.locator('.ck-feed-body')
    await expect(feedBody).toBeVisible()

    const feedBefore = await feedBody.evaluate((el) => el.scrollTop)
    await stage.evaluate((el) => { el.scrollTop = el.scrollHeight })
    await page.waitForTimeout(300)
    const feedAfterGanttScroll = await feedBody.evaluate((el) => el.scrollTop)
    expect(feedAfterGanttScroll).toBe(feedBefore)

    const stageBefore = await stage.evaluate((el) => el.scrollTop)
    await feedBody.evaluate((el) => { el.scrollTop = el.scrollHeight })
    await page.waitForTimeout(300)
    const stageAfterFeedScroll = await stage.evaluate((el) => el.scrollTop)
    expect(stageAfterFeedScroll).toBe(stageBefore)
  })

  test('clicking a feed item still jumps the gantt to that event and flashes it (click nav kept)', async ({ page }) => {
    await openCockpit(page)
    const targetHead = page.locator('.ck-feed-evhead[data-event="FIX-5"]')
    await expect(targetHead).toBeVisible()
    await targetHead.click()
    const lane = page.locator('.ck-lane[data-event="FIX-5"]')
    await expect(lane).toBeVisible()
    await expect(lane).toHaveClass(/\bck-flash\b/)
    const box = await lane.boundingBox()
    const stageBox = await page.locator('.ck-stage').boundingBox()
    expect(box.y).toBeGreaterThanOrEqual(stageBox.y - 4)
    expect(box.y).toBeLessThanOrEqual(stageBox.y + stageBox.height + 4)
  })

  test('the machine board is mounted below the gantt by default, and keeps polling', async ({ page }) => {
    await openCockpit(page)
    const railBtn = page.locator('.ck-rail-btn[data-goto="machines"]')
    await expect(railBtn).toBeVisible()
    await expect(railBtn).not.toHaveAttribute('hidden', '')

    const block = page.locator('.ck-block-machines[data-module="machines"]')
    await expect(block).toBeVisible()
    await expect(page.locator('.mach-card', { hasText: 'Fixture Local' })).toBeVisible({ timeout: 15_000 })
  })

  test('no console errors on the cockpit home page', async ({ page }) => {
    const errors = []
    page.on('pageerror', (e) => errors.push(String(e)))
    page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()) })
    await openCockpit(page)
    await page.waitForTimeout(500)
    expect(errors).toEqual([])
  })
})

test.describe('cockpit desktop screenshot (1440x900)', () => {
  test.use({ viewport: { width: 1440, height: 900 } })
  test('gantt + feed + machine board all visible', async ({ page }) => {
    await page.goto('/')
    await expect(page.locator('.ck-lane[data-event]').first()).toBeVisible({ timeout: 10_000 })
    await expect(page.locator('.ck-block-machines')).toBeVisible()
    await page.locator('.ck-block-machines').scrollIntoViewIfNeeded()
    await page.waitForTimeout(300)
    await page.screenshot({ path: process.env.SHOT_DESKTOP, fullPage: false })
  })
})

test.describe('cockpit mobile screenshot (390x844)', () => {
  test.use({ viewport: { width: 390, height: 844 } })
  test('gantt visible, feed drawer opens, machine board reachable', async ({ page }) => {
    await page.goto('/')
    await expect(page.locator('.ck-lane[data-event]').first()).toBeVisible({ timeout: 10_000 })
    await page.locator('.ck-feed-open').click()
    await expect(page.locator('.cockpit.ck-feed-shown')).toBeVisible()
    await page.waitForTimeout(300)
    await page.screenshot({ path: process.env.SHOT_MOBILE, fullPage: false })

    // The machine board is also reachable from the bottom tab bar on mobile.
    await page.locator('.ck-feed-close').click()
    await page.locator('.ck-rail-btn[data-goto="machines"]').click()
    await expect(page.locator('.ck-block-machines')).toBeVisible()
    await page.waitForTimeout(300)
    if (process.env.SHOT_MOBILE_MACHINES) await page.screenshot({ path: process.env.SHOT_MOBILE_MACHINES, fullPage: false })
  })
})
